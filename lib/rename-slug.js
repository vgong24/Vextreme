'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const TEXT_EXTENSIONS = new Set([
  '', '.css', '.html', '.js', '.json', '.md', '.mjs', '.ps1', '.sh', '.txt', '.xml', '.yaml', '.yml',
]);
const SKIP_DIRS = new Set(['.git', 'node_modules']);
const GENERATED_PATHS = new Set([
  'data/analysis-index.json',
  'data/index.json',
  'data/page-health.json',
  'data/status.json',
  'data/terrain-map.json',
  'docs/architecture.md',
  'index.html',
  'pages/archives.html',
  'pages/build-health.html',
  'sitemap.xml',
  'sw.js',
]);
const LIVE_ROOT_FILES = new Set(['CLAUDE.md', 'README.md']);

function slash(value) {
  return String(value).split(path.sep).join('/');
}

function assertSlug(value, label) {
  if (!SLUG_RE.test(String(value || ''))) throw new TypeError(`${label} must be a lowercase kebab-case slug`);
  return value;
}

function listFallbackFiles(root) {
  const found = [];
  function visit(relativeDir) {
    const absoluteDir = path.join(root, relativeDir);
    for (const entry of fs.readdirSync(absoluteDir, { withFileTypes: true })) {
      if (SKIP_DIRS.has(entry.name)) continue;
      const relative = relativeDir ? path.join(relativeDir, entry.name) : entry.name;
      if (entry.isDirectory()) visit(relative);
      else if (entry.isFile()) found.push(slash(relative));
    }
  }
  visit('');
  return found.sort();
}

function listSourceFiles(root) {
  try {
    const raw = execFileSync('git', ['-C', root, 'ls-files', '-z'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
    const files = raw.split('\0').filter(Boolean).map(slash).sort();
    if (files.length > 0) return files;
  } catch (_) {}
  return listFallbackFiles(root);
}

function isTextPath(relativePath) {
  return TEXT_EXTENSIONS.has(path.extname(relativePath).toLowerCase());
}

function countOccurrences(text, needle) {
  if (!needle) return 0;
  let count = 0;
  let cursor = 0;
  while ((cursor = text.indexOf(needle, cursor)) !== -1) {
    count += 1;
    cursor += needle.length;
  }
  return count;
}

function classifyReference(relativePath, fromSlug) {
  const p = slash(relativePath);
  if (p === `pages/${fromSlug}.html` || p === 'config/institutional-surfaces.json') return 'LIVE_OWNER';
  if (p.startsWith('tests/')) return 'TEST_EXPECTATION';
  if (p.startsWith('docs/continuity/') || p.startsWith('docs/ingestion/')) return 'HISTORICAL_PROVENANCE';
  if (p.startsWith('docs/screenshots/') || p === 'data/screenshot-evidence-assets.json') return 'SCREENSHOT_EVIDENCE';
  if (GENERATED_PATHS.has(p) || p.startsWith('dist/')) return 'GENERATED';
  if (
    LIVE_ROOT_FILES.has(p)
    || p === 'docs/culture.md'
    || p === 'docs/lattice-map.json'
    || p.startsWith('docs/architecture/')
    || p.startsWith('pages/')
    || p.startsWith('widgets/')
    || p.startsWith('scripts/')
    || p.startsWith('lib/')
    || p.startsWith('components/')
    || p.startsWith('config/')
    || p.startsWith('data/strings/source/')
    || p.startsWith('.github/')
  ) return 'LIVE_REFERENCE';
  return 'UNKNOWN';
}

function discoverReferences(root, fromSlug, files = listSourceFiles(root)) {
  const references = [];
  for (const relativePath of files) {
    const filenameMatch = relativePath.includes(fromSlug);
    let contentCount = 0;
    if (isTextPath(relativePath)) {
      try {
        const text = fs.readFileSync(path.join(root, relativePath), 'utf8');
        contentCount = countOccurrences(text, fromSlug);
      } catch (_) {}
    }
    if (!filenameMatch && contentCount === 0) continue;
    references.push({
      path: relativePath,
      classification: classifyReference(relativePath, fromSlug),
      filenameMatch,
      contentCount,
    });
  }
  return references.sort((a, b) => a.path.localeCompare(b.path));
}

function readJsonIfPresent(root, relativePath) {
  const absolute = path.join(root, relativePath);
  if (!fs.existsSync(absolute)) return null;
  return JSON.parse(fs.readFileSync(absolute, 'utf8'));
}

function detectTargetCollisions(root, toSlug, files = listSourceFiles(root)) {
  const collisions = [];
  const exactPaths = [
    `pages/${toSlug}.html`,
    `wip/${toSlug}.html`,
    `dist/vextreme-${toSlug}.js`,
    `data/strings/source/pages/${toSlug}.json`,
  ];
  for (const candidate of exactPaths) {
    if (files.includes(candidate) || fs.existsSync(path.join(root, candidate))) collisions.push({ kind: 'PATH_EXISTS', path: candidate });
  }

  const registry = readJsonIfPresent(root, 'config/institutional-surfaces.json');
  if (registry && registry.surfaces && Object.prototype.hasOwnProperty.call(registry.surfaces, toSlug)) {
    collisions.push({ kind: 'INSTITUTIONAL_SLUG_EXISTS', path: 'config/institutional-surfaces.json' });
  }

  const nodes = readJsonIfPresent(root, 'data/nodes.json');
  if (Array.isArray(nodes) && nodes.some((node) => node && node.slug === toSlug)) {
    collisions.push({ kind: 'NODE_SLUG_EXISTS', path: 'data/nodes.json' });
  }

  for (const relativePath of files.filter((p) => p.startsWith('wip/') && p.endsWith('.json'))) {
    try {
      const value = JSON.parse(fs.readFileSync(path.join(root, relativePath), 'utf8'));
      if (value && value._meta && value._meta.slug === toSlug) collisions.push({ kind: 'WIP_DECLARED_SLUG_EXISTS', path: relativePath });
    } catch (_) {}
  }
  return collisions.sort((a, b) => a.path.localeCompare(b.path) || a.kind.localeCompare(b.kind));
}

function institutionalPreconditions(root, fromSlug) {
  const errors = [];
  const pagePath = `pages/${fromSlug}.html`;
  if (!fs.existsSync(path.join(root, pagePath))) errors.push({ kind: 'OLD_PAGE_MISSING', path: pagePath });
  const registry = readJsonIfPresent(root, 'config/institutional-surfaces.json');
  const surface = registry && registry.surfaces && registry.surfaces[fromSlug];
  if (!surface) errors.push({ kind: 'OLD_INSTITUTIONAL_OWNER_MISSING', path: 'config/institutional-surfaces.json' });
  else if (surface.kind !== 'institutional') errors.push({ kind: 'OLD_OWNER_KIND_MISMATCH', path: 'config/institutional-surfaces.json' });
  return { ok: errors.length === 0, errors };
}

function canonicalPlanValue(plan) {
  return {
    schemaVersion: plan.schemaVersion,
    fromSlug: plan.fromSlug,
    toSlug: plan.toSlug,
    kind: plan.kind,
    preconditions: plan.preconditions,
    collisions: plan.collisions,
    references: plan.references,
    summary: plan.summary,
    applyReady: plan.applyReady,
    mutationSupported: plan.mutationSupported,
  };
}

function fingerprintPlan(plan) {
  return crypto.createHash('sha256').update(JSON.stringify(canonicalPlanValue(plan))).digest('hex');
}

function planInstitutionalSlugRename({ root, fromSlug, toSlug }) {
  assertSlug(fromSlug, 'fromSlug');
  assertSlug(toSlug, 'toSlug');
  if (fromSlug === toSlug) throw new TypeError('fromSlug and toSlug must differ');
  const files = listSourceFiles(root);
  const references = discoverReferences(root, fromSlug, files);
  const collisions = detectTargetCollisions(root, toSlug, files);
  const preconditions = institutionalPreconditions(root, fromSlug);
  const counts = {};
  for (const reference of references) counts[reference.classification] = (counts[reference.classification] || 0) + 1;
  const unknownCount = counts.UNKNOWN || 0;
  const plan = {
    schemaVersion: 'vextreme.slug-rename-plan/v1',
    fromSlug,
    toSlug,
    kind: 'institutional',
    preconditions,
    collisions,
    references,
    summary: {
      referenceCount: references.length,
      countsByClassification: Object.fromEntries(Object.entries(counts).sort(([a], [b]) => a.localeCompare(b))),
      unknownCount,
    },
    applyReady: preconditions.ok && collisions.length === 0 && unknownCount === 0,
    mutationSupported: false,
  };
  plan.planSha256 = fingerprintPlan(plan);
  return plan;
}

function parseArgs(argv) {
  const options = { root: path.resolve(__dirname, '..'), plan: false, json: false, kind: null, fromSlug: null, toSlug: null };
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (token === '--plan') options.plan = true;
    else if (token === '--json') options.json = true;
    else if (token === '--root') options.root = path.resolve(argv[++i] || '');
    else if (token === '--from') options.fromSlug = argv[++i] || null;
    else if (token === '--to') options.toSlug = argv[++i] || null;
    else if (token === '--kind') options.kind = argv[++i] || null;
    else throw new TypeError(`unknown argument: ${token}`);
  }
  if (!options.plan) throw new TypeError('plan-only row requires --plan');
  if (options.kind !== 'institutional') throw new TypeError('only --kind institutional is supported in this row');
  if (!options.fromSlug || !options.toSlug) throw new TypeError('--from and --to are required');
  return options;
}

function renderHumanPlan(plan) {
  const lines = [
    `Slug rename plan: ${plan.fromSlug} -> ${plan.toSlug} (${plan.kind})`,
    `planSha256: ${plan.planSha256}`,
    `preconditions: ${plan.preconditions.ok ? 'PASS' : 'FAIL'}`,
    `collisions: ${plan.collisions.length}`,
    `references: ${plan.summary.referenceCount}`,
    `unknown: ${plan.summary.unknownCount}`,
    `applyReady: ${plan.applyReady}`,
    `mutationSupported: ${plan.mutationSupported}`,
  ];
  let last = null;
  for (const reference of plan.references) {
    if (reference.classification !== last) {
      last = reference.classification;
      lines.push('', last);
    }
    const modes = [reference.filenameMatch ? 'filename' : null, reference.contentCount ? `content:${reference.contentCount}` : null].filter(Boolean).join(',');
    lines.push(`  ${reference.path}${modes ? ` (${modes})` : ''}`);
  }
  if (plan.collisions.length) {
    lines.push('', 'COLLISIONS');
    for (const collision of plan.collisions) lines.push(`  ${collision.kind}: ${collision.path}`);
  }
  if (plan.preconditions.errors.length) {
    lines.push('', 'PRECONDITION_ERRORS');
    for (const error of plan.preconditions.errors) lines.push(`  ${error.kind}: ${error.path}`);
  }
  return lines.join('\n');
}

function run(argv = process.argv.slice(2)) {
  const options = parseArgs(argv);
  const plan = planInstitutionalSlugRename({ root: options.root, fromSlug: options.fromSlug, toSlug: options.toSlug });
  process.stdout.write(options.json ? `${JSON.stringify(plan, null, 2)}\n` : `${renderHumanPlan(plan)}\n`);
  return plan;
}

if (require.main === module) {
  try { run(); }
  catch (error) {
    console.error(`[rename-slug] ${error.message}`);
    process.exit(1);
  }
}

module.exports = {
  SLUG_RE,
  classifyReference,
  detectTargetCollisions,
  discoverReferences,
  fingerprintPlan,
  institutionalPreconditions,
  listSourceFiles,
  planInstitutionalSlugRename,
  renderHumanPlan,
  run,
};

