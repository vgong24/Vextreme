#!/usr/bin/env node
/**
 * VEXTREME — lib/build-shared-cache-generation.js
 *
 * Derives the legacy shell/runtime cache token from the actual cache-family
 * source bytes instead of a hand-maintained integer.
 *
 * The two source files that carry the token are normalized to a stable
 * placeholder before hashing. That makes the generated token independent of
 * its previous value, so repeated generation converges and parallel branches
 * derive identity from their composed bytes rather than competing for v18/v19.
 *
 * Run manually:
 *   node lib/build-shared-cache-generation.js
 *   node lib/build-shared-cache-generation.js --check
 *
 * Cache identity:
 *   sha256(sorted(path + NUL + normalizedBytes + NUL)).slice(0, 12)
 *   -> ?v=<12 lowercase hex>
 *
 * LATTICE:BEGIN — generated by lib/build-lattice-headers.js from docs/lattice-map.json. Do not hand-edit; edit the JSON and regenerate.
 *   role      : deterministic shared-runtime cache identity generator — fingerprints the cache-versioned v1 shell/runtime asset family after normalizing token-bearing lines, then writes one convergent content-derived token into shell.js, vextreme.js and Terrain's shell bootstrap
 *   reads     : lib/shell.js and lib/vextreme.js (token-bearing source normalized before hashing)
 *               lib/arc-nav.js and lib/archive-renderer.js
 *               components/section-toggle.js and components/bc-nav.js
 *               widgets/vex-fab.js / fab-read-aloud.js / fab-lang.js / fab-theme.js / fab-map.js
 *               styles/site-nav.css / squarespace-overrides.css / design-system.css / arc-nav.css / page template CSS
 *               data/arcs.json and data/pages.json
 *   writes    : lib/shell.js VEXTREME_VER
 *               lib/vextreme.js DEFAULT_CACHE
 *               pages/terrain-map.html shell.js query token
 *   loaded-by : package.json cache:build / cache:check / pr-ready
 *               tests/41-vextreme-fab-autoload.test.js
 *   tested-by : tests/41-vextreme-fab-autoload.test.js
 *
 *   CHANGE MAP — if you touch X here, also check:
 *     CACHE_FAMILY_PATHS membership changes:
 *       - lib/vextreme.js cacheVer consumers — every same-token runtime fetch/load must stay represented
 *       - tests/41 cache-family fingerprint regression
 *       - docs/lattice-map.json reads list here
 *     token normalization or rewrite contract changes:
 *       - lib/shell.js VEXTREME_VER
 *       - lib/vextreme.js DEFAULT_CACHE
 *       - pages/terrain-map.html shell bootstrap
 *       - tests/41 convergence + currentness checks
 * LATTICE:END
 */

'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');

const CACHE_FAMILY_PATHS = Object.freeze([
  'lib/shell.js',
  'lib/vextreme.js',
  'lib/arc-nav.js',
  'lib/archive-renderer.js',
  'components/section-toggle.js',
  'components/bc-nav.js',
  'widgets/vex-fab.js',
  'widgets/fab-read-aloud.js',
  'widgets/fab-lang.js',
  'widgets/fab-theme.js',
  'widgets/fab-map.js',
  'styles/site-nav.css',
  'styles/squarespace-overrides.css',
  'styles/design-system.css',
  'styles/arc-nav.css',
  'styles/page-templates/journal-qa.css',
  'styles/page-templates/bridge-council.css',
  'styles/page-templates/ascension-embodiment.css',
  'data/arcs.json',
  'data/pages.json',
]);

const SHELL_TOKEN_RE = /var VEXTREME_VER\s*=\s*'\?v=[^']+';/u;
const RUNTIME_TOKEN_RE = /var DEFAULT_CACHE\s*=\s*'\?v=[^']+';/u;
const TERRAIN_TOKEN_RE = /<script src="\.\.\/lib\/shell\.js\?v=[^"]+"><\/script>/u;
const TOKEN_RE = /^\?v=[a-f0-9]{12}$/u;
const NORMALIZED_TOKEN = '?v=<CACHE>';

function normalizeVersionOwnedSource(relativePath, source) {
  const text = Buffer.isBuffer(source) ? source.toString('utf8') : String(source);
  if (relativePath === 'lib/shell.js') {
    if (!SHELL_TOKEN_RE.test(text)) throw new Error('CACHE_IDENTITY_SHELL_TOKEN_MISSING');
    return text.replace(SHELL_TOKEN_RE, `var VEXTREME_VER = '${NORMALIZED_TOKEN}';`);
  }
  if (relativePath === 'lib/vextreme.js') {
    if (!RUNTIME_TOKEN_RE.test(text)) throw new Error('CACHE_IDENTITY_RUNTIME_TOKEN_MISSING');
    return text.replace(RUNTIME_TOKEN_RE, `var DEFAULT_CACHE = '${NORMALIZED_TOKEN}';`);
  }
  return text;
}

function computeFingerprintFromEntries(entries) {
  const hash = crypto.createHash('sha256');
  for (const [relativePath, source] of [...entries].sort(([a], [b]) => a.localeCompare(b))) {
    hash.update(relativePath);
    hash.update('\0');
    hash.update(normalizeVersionOwnedSource(relativePath, source));
    hash.update('\0');
  }
  return hash.digest('hex').slice(0, 12);
}

function computeSharedCacheFingerprint(root = ROOT) {
  const entries = CACHE_FAMILY_PATHS.map((relativePath) => {
    const file = path.join(root, relativePath);
    if (!fs.existsSync(file) || !fs.statSync(file).isFile()) {
      throw new Error(`CACHE_IDENTITY_SOURCE_MISSING:${relativePath}`);
    }
    return [relativePath, fs.readFileSync(file)];
  });
  return computeFingerprintFromEntries(entries);
}

function expectedCacheToken(root = ROOT) {
  return `?v=${computeSharedCacheFingerprint(root)}`;
}

function readCacheTokens(root = ROOT) {
  const shell = fs.readFileSync(path.join(root, 'lib', 'shell.js'), 'utf8');
  const runtime = fs.readFileSync(path.join(root, 'lib', 'vextreme.js'), 'utf8');
  const terrain = fs.readFileSync(path.join(root, 'pages', 'terrain-map.html'), 'utf8');
  const shellMatch = shell.match(/var VEXTREME_VER\s*=\s*'(\?v=[^']+)';/u);
  const runtimeMatch = runtime.match(/var DEFAULT_CACHE\s*=\s*'(\?v=[^']+)';/u);
  const terrainMatch = terrain.match(/<script src="\.\.\/lib\/shell\.js(\?v=[^"]+)"><\/script>/u);
  if (!shellMatch || !runtimeMatch || !terrainMatch) throw new Error('CACHE_IDENTITY_TOKEN_OWNER_MISSING');
  return Object.freeze({ shell: shellMatch[1], runtime: runtimeMatch[1], terrain: terrainMatch[1] });
}

function rewriteCacheToken(relativePath, source, token) {
  if (!TOKEN_RE.test(token)) throw new Error(`CACHE_IDENTITY_TOKEN_INVALID:${token}`);
  if (relativePath === 'lib/shell.js') {
    if (!SHELL_TOKEN_RE.test(source)) throw new Error('CACHE_IDENTITY_SHELL_TOKEN_MISSING');
    return source.replace(SHELL_TOKEN_RE, `var VEXTREME_VER = '${token}';`);
  }
  if (relativePath === 'lib/vextreme.js') {
    if (!RUNTIME_TOKEN_RE.test(source)) throw new Error('CACHE_IDENTITY_RUNTIME_TOKEN_MISSING');
    return source.replace(RUNTIME_TOKEN_RE, `var DEFAULT_CACHE = '${token}';`);
  }
  if (relativePath === 'pages/terrain-map.html') {
    if (!TERRAIN_TOKEN_RE.test(source)) throw new Error('CACHE_IDENTITY_TERRAIN_TOKEN_MISSING');
    return source.replace(TERRAIN_TOKEN_RE, `<script src="../lib/shell.js${token}"></script>`);
  }
  return source;
}

function updateSharedCacheGeneration({ root = ROOT, check = false } = {}) {
  const token = expectedCacheToken(root);
  const owners = ['lib/shell.js', 'lib/vextreme.js', 'pages/terrain-map.html'];
  const before = readCacheTokens(root);
  const current = [before.shell, before.runtime, before.terrain];
  const allCurrent = current.every((value) => value === token);
  if (check) {
    if (!allCurrent) {
      throw new Error(`CACHE_IDENTITY_STALE:expected=${token}:observed=${current.join(',')}`);
    }
    return Object.freeze({ state: 'CURRENT', changed: false, token });
  }

  let changed = false;
  for (const relativePath of owners) {
    const file = path.join(root, relativePath);
    const source = fs.readFileSync(file, 'utf8');
    const next = rewriteCacheToken(relativePath, source, token);
    if (next !== source) {
      fs.writeFileSync(file, next, 'utf8');
      changed = true;
    }
  }

  const after = readCacheTokens(root);
  if (![after.shell, after.runtime, after.terrain].every((value) => value === token)) {
    throw new Error('CACHE_IDENTITY_WRITE_VERIFY_FAILED');
  }
  if (expectedCacheToken(root) !== token) {
    throw new Error('CACHE_IDENTITY_NON_CONVERGENT');
  }
  return Object.freeze({ state: 'CURRENT', changed, token });
}

function main() {
  try {
    const check = process.argv.includes('--check');
    const result = updateSharedCacheGeneration({ check });
    console.log(`[build-shared-cache-generation] ${result.state}`);
    console.log(`  token   : ${result.token}`);
    console.log(`  changed : ${result.changed}`);
  } catch (error) {
    console.error(`[build-shared-cache-generation] ${error.message}`);
    if (process.argv.includes('--check')) {
      console.error('Run: npm run cache:build');
    }
    process.exit(1);
  }
}

if (require.main === module) main();

module.exports = {
  CACHE_FAMILY_PATHS,
  NORMALIZED_TOKEN,
  normalizeVersionOwnedSource,
  computeFingerprintFromEntries,
  computeSharedCacheFingerprint,
  expectedCacheToken,
  readCacheTokens,
  rewriteCacheToken,
  updateSharedCacheGeneration,
};

