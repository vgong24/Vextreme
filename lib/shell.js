(function () {
  'use strict';

  var DEFAULT_BASE = 'https://cdn.jsdelivr.net/gh/vgong24/vextreme@main';
  var shellScript = document.currentScript;
  var shellUrl = null;
  try { shellUrl = shellScript && shellScript.src ? new URL(shellScript.src, document.baseURI) : null; }
  catch (e) {}
  var BASE = shellUrl && shellUrl.origin === window.location.origin
    ? shellUrl.href.replace(/\/lib\/shell\.js(?:\?.*)?$/, '')
    : DEFAULT_BASE;

  // Generated from the shared cache-family bytes. This exact token is also
  // written into vextreme.js DEFAULT_CACHE and Terrain's shell bootstrap.
  var VEXTREME_VER = '?v=92abdcec2f23';

  var el    = document.createElement('script');
  el.src    = BASE + '/lib/vextreme.js' + VEXTREME_VER;
  el.onload = function () {
    if (typeof window.VEXTREME === 'function') {
      var override = window.VEXTREME_OVERRIDE || {};
      if (shellUrl && shellUrl.origin === window.location.origin && !override.baseUrl) {
        override = Object.assign({}, override, { baseUrl: BASE });
      }
      window.VEXTREME(override);
    } else {
      console.warn('[VEXTREME shell] vextreme.js loaded but VEXTREME not defined');
    }
  };
  el.onerror = function () {
    console.warn('[VEXTREME shell] Failed to load vextreme.js from: ' + el.src);
  };
  document.head.appendChild(el);

}());
