// ── Date parsing ─────────────────────────────────────────────────────────────

const MONTH_INDEX = Object.freeze({
  jan: 0, january: 0,
  feb: 1, february: 1,
  mar: 2, march: 2,
  apr: 3, april: 3,
  may: 4,
  jun: 5, june: 5,
  jul: 6, july: 6,
  aug: 7, august: 7,
  sep: 8, sept: 8, september: 8,
  oct: 9, october: 9,
  nov: 10, november: 10,
  dec: 11, december: 11,
});

function parseDateParts(str) {
  if (typeof str !== 'string' || !str.trim()) return null;
  const match = str.trim().match(/^([A-Za-z]+)\s+(\d{1,2})(?:[–-]\d{1,2})?,\s+(\d{4})$/);
  if (!match) return null;

  const month = MONTH_INDEX[match[1].toLowerCase()];
  const day = Number(match[2]);
  const year = Number(match[3]);
  if (month === undefined || day < 1 || day > 31) return null;

  // Validate calendar overflow (for example, February 31) without relying on
  // Date's implementation-defined parsing of English strings.
  const probe = new Date(year, month, day, 12, 0, 0, 0);
  if (probe.getFullYear() !== year || probe.getMonth() !== month || probe.getDate() !== day) return null;
  return { year, month, day };
}

function parseDate(str) {
  const parts = parseDateParts(str);
  if (!parts) return null;
  // Local noon keeps calendar accessors stable on UTC-negative and
  // UTC-positive machines. Persistence uses toDateISO(), not toISOString().
  return new Date(parts.year, parts.month, parts.day, 12, 0, 0, 0);
}

function toDateISO(str) {
  const parts = parseDateParts(str);
  if (!parts) return null;
  return `${String(parts.year).padStart(4, '0')}-${String(parts.month + 1).padStart(2, '0')}-${String(parts.day).padStart(2, '0')}`;
}

// ── Pure computation functions ────────────────────────────────────────────────

function contentFingerprint(value) {
  return crypto.createHash('sha256').update(JSON.stringify(value)).digest('hex').slice(0, 12);
}

// buildPageLanguageCoverage — derives page-local language truth from the
// already-generated scope index. Translation ownership stays locale + canonical
// key; this is only a page/runtime projection.
//
// availableLangs: EN plus any locale with at least one translated key in one of
// the page's declared scopes. Common UI alone never makes a page advertise a
// locale.
//
// completeLangs: EN plus any locale whose every runtime-required scope
// (common + declared page scopes) has the same key count as EN. This stricter
// set is what downstream localized screenshot evidence can safely consume.
function buildPageLanguageCoverage(scopes, scopeIndex) {
  const declaredScopes = Array.from(new Set((scopes || []).filter(Boolean)));
  const pageScopes = declaredScopes.filter(scope => scope !== Scope.COMMON);
  const requiredScopes = Array.from(new Set([Scope.COMMON, ...declaredScopes]));
  const index = scopeIndex || {};

  const available = new Set([Language.EN]);
  const candidates = new Set();

  function addNumericLocales(record, target) {
    for (const [lang, count] of Object.entries(record || {})) {
      if (typeof count !== 'number' || count <= 0) continue;
      target.add(lang);
    }
  }

  for (const scope of pageScopes) {
    addNumericLocales(index[scope], available);
  }
  for (const scope of requiredScopes) {
    addNumericLocales(index[scope], candidates);
  }

  const complete = new Set([Language.EN]);
  for (const lang of candidates) {
    if (lang === Language.EN) continue;
    const allComplete = requiredScopes.every(scope => {
      const record = index[scope];
      if (!record) return false;
      const enCount = Number(record[Language.EN] || 0);
      return enCount > 0 && Number(record[lang] || 0) === enCount;
    });
    if (allComplete) complete.add(lang);
  }

  const ordered = values => [
    ...(values.has(Language.EN) ? [Language.EN] : []),
    ...Array.from(values).filter(lang => lang !== Language.EN).sort(),
  ];

  return {
    availableLangs: ordered(available),
    completeLangs: ordered(complete),
  };
}

// buildViewmodel — derives the per-page viewmodel for a slug.
// Merges the slug's override from data/viewmodels.json with safe defaults.
// The viewmodel remains the build/runtime contract for category, template,
// scopes, and features; translation coverage is a separate derived read model.
function buildViewmodel(slug, viewmodels) {
  const override = (viewmodels || {})[slug] || {};
  return {
    category: override.category || DEFAULT_CATEGORY,
    template: override.template || 'page',
    scopes:   override.scopes   || [`pages.${slug}`],
    features: override.features || [Feature.LANG, Feature.SPIRAL_FAB, Feature.THEME, Feature.MAP, Feature.ANALYSIS],
  };
}

// buildSlugMap — O(1) lookup table from slug → node with derived fields.
// arcKeys re-sorted by arc priority so the browser renders in correct order.
// viewmodels is the parsed data/viewmodels.json override map (optional).
function buildSlugMap(nodes, arcsDef, viewmodels) {
  const slugMap = {};
  for (const node of nodes) {
    const sortedArcKeys = node.arcKeys.slice().sort((a, b) => {
      const pa = arcsDef[a]?.priority ?? 50;
      const pb = arcsDef[b]?.priority ?? 50;
      return pa - pb;
    });
    slugMap[node.slug] = {
      ...node,
      arcKeys:   sortedArcKeys,
      dateISO:   toDateISO(node.date),
      viewmodel: buildViewmodel(node.slug, viewmodels),
    };
  }
  return slugMap;
}

// buildPageLanguageMap — one generated read model for every page/viewmodel slug.
// It reuses each page's declared scopes and the compiled scope index; no page,
// arc, or work shard becomes a translation owner.
function buildPageLanguageMap(slugMap, viewmodels, scopeIndex) {
  const result = {};

  for (const [slug, entry] of Object.entries(slugMap || {})) {
    const scopes = entry && entry.viewmodel ? entry.viewmodel.scopes : [`pages.${slug}`];
    result[slug] = buildPageLanguageCoverage(scopes, scopeIndex);
  }

  for (const [slug, override] of Object.entries(viewmodels || {})) {
    if (slug.startsWith('_') || result[slug]) continue;
    const scopes = override.scopes || [`pages.${slug}`];
    result[slug] = buildPageLanguageCoverage(scopes, scopeIndex);
  }

  return result;
}

// declaredShellStringScopes — shell-era pages that are intentionally outside
// slugMap/viewmodel ownership may still declare canonical string scopes. The
// shared shell is the runtime boundary; scope declarations without shell.js do
// not create a page-language projection.
function declaredShellStringScopes(html) {
  const source = String(html || '');
  if (!/<script\b[^>]*src=["'][^"']*\/lib\/shell\.js(?:\?[^"']*)?["'][^>]*>/i.test(source)) return [];
  const match = source.match(/window\.VEX_STRING_SCOPES\s*=\s*(\[[^;\n]*\])\s*;/);
  if (!match) return [];
  let parsed;
  try { parsed = JSON.parse(match[1]); } catch (_) { return []; }
  if (!Array.isArray(parsed) || parsed.some(scope => typeof scope !== 'string' || !scope)) return [];
  return Array.from(new Set(parsed));
}

// extendPageLanguageMapWithShellPages — project page-local completion for
// explicit shell surfaces without turning those pages into a second locale
// registry. Existing slugMap/viewmodel entries remain authoritative.
function extendPageLanguageMapWithShellPages(pageLanguageMap, pageSlugs, scopeIndex, readHtml) {
  const result = { ...(pageLanguageMap || {}) };
  for (const slug of pageSlugs || []) {
    if (!slug || result[slug]) continue;
    const scopes = declaredShellStringScopes(readHtml(slug));
    if (!scopes.length) continue;
    result[slug] = buildPageLanguageCoverage(scopes, scopeIndex);
  }
  return result;
}

// buildSourceOnlyScopes — projects translation-policy scopes already owned by
// data/strings/compiled/scopes/index.json into the site index. Downstream read
// models consume this projection instead of growing their own scope-index edge.
function buildSourceOnlyScopes(scopeIndex) {
  return Object.entries(scopeIndex || {})
    .filter(([, record]) => record && record.translationPolicy === 'source-only')
    .map(([scope]) => scope)
    .sort();
}

// buildArcMap — resolves each arc's sections into ordered slug lists.
// Supports 'explicit' (manually ordered) and 'chronological' (date-sorted) sections.
function buildArcMap(nodes, arcsDef, slugMap) {
  const arcMap = {};

  for (const [arcName, arcDef] of Object.entries(arcsDef)) {
    if (arcName.startsWith('_')) continue;

    const resolvedSections = [];

    for (const section of arcDef.sections) {
      let orderedSlugs = [];

      if (section.order === 'explicit') {
        orderedSlugs = (section.slugs || []).filter(slug => {
          if (!slugMap[slug]) {
            logger.warn({ code: CODES.SLUG_NOT_IN_NODES, message: `slug not in nodes.json — skipped`, arc: arcName, section: section.label, slug });
            return false;
          }
          return true;
        });

      } else {
        // chronological — filter nodes whose arcKeys include this arc
        let items = nodes.filter(n => n.arcKeys.includes(arcName));

        // Narrow by dateRange if defined (required for full_timeline sections)
        if (section.dateRange) {
          items = items.filter(n => {
            const dateISO = toDateISO(n.date);
            return dateISO !== null &&
              dateISO >= section.dateRange.from &&
              dateISO <= section.dateRange.to;
          });
        }

        items.sort((a, b) => {
          const da = parseDate(a.date);
          const db = parseDate(b.date);
          if (da === null && db === null) return 0;
          if (da === null) return 1;
          if (db === null) return -1;
          return da - db;
        });

        orderedSlugs = items.map(n => n.slug);
      }

      if (orderedSlugs.length > 0) {
        resolvedSections.push({ label: section.label, slugs: orderedSlugs });
      }
    }

    arcMap[arcName] = resolvedSections;
  }

  return arcMap;
}

// buildSupportedLangs — scans compiled strings directory for available bundles.
// Automatic: adding a new language to the strings pipeline makes it appear here.
function buildSupportedLangs() {
  const compiledDir = path.join(ROOT, 'data', 'strings', 'compiled');
  try {
    return fs.readdirSync(compiledDir)
      .filter(f => /^strings\.[a-z]{2,}\.json$/.test(f))
      .map(f => f.replace(/^strings\./, '').replace(/\.json$/, ''))
      .sort();
  } catch (e) {
    return [Language.EN];
  }
}

// buildArcMeta — extracts display metadata from arc definitions.
// Stored in index.json so the browser has no hard-coded arc tables.
function buildArcMeta(arcsDef) {
  const arcMeta = {};
  for (const [arcName, arcDef] of Object.entries(arcsDef)) {
    if (arcName.startsWith('_')) continue;
    arcMeta[arcName] = {
      title:      arcDef.parent?.title  ?? arcName,
      url:        arcDef.parent?.url    ?? '#',
      renderMode: arcDef.renderMode     ?? 'dots'
    };
    // bundlingStrategy is opt-in and rare (od-001/td-006 pilot) — only carried
    // through when an arc actually declares one, so index.json stays clean
    // for the other 16 arcs that never touch this field.
    if (arcDef.bundlingStrategy) arcMeta[arcName].bundlingStrategy = arcDef.bundlingStrategy;
  }
  return arcMeta;
}

// findDuplicateSlugs — BLOCK-severity guard: slug is the system's only identifier
// (docs/architecture/02-slug.md), so two nodes sharing a slug isn't a warning-level
// drift the way a stale index.json is — it's the map-based lookup (department →
// workType → slug → pages/{slug}.html) silently pointing at the wrong file, or
// buildSlugMap silently overwriting one node with another. Returns an array of
// { slug, count } for every slug that appears more than once; empty means clean.
function findDuplicateSlugs(nodes) {
  const counts = {};
  for (const node of nodes) {
    counts[node.slug] = (counts[node.slug] || 0) + 1;
  }
  return Object.entries(counts)
    .filter(([, count]) => count > 1)
    .map(([slug, count]) => ({ slug, count }));
}

// buildDepartmentMap — groups nodes by production-domain department + workType,
// a different axis than arcMap (reader-facing narrative grouping). A node with no
// department/workType field falls back to whichever department is marked default:true
// (and that department's 'default' workType). Each entry carries `ported` — whether
// pages/{slug}.html exists — the same ported-vs-not signal build-archives.js already
// computes per-arc, surfaced here per-department instead.
function buildDepartmentMap(nodes, departmentsDef) {
  const defaultDept = Object.keys(departmentsDef || {})
    .filter(id => !id.startsWith('_'))
    .find(id => departmentsDef[id].default) || 'rd';

  const map = {};
  for (const node of nodes) {
    const dept     = node.department || defaultDept;
    const workType = node.workType   || 'default';

    if (!map[dept]) map[dept] = {};
    if (!map[dept][workType]) map[dept][workType] = [];

    map[dept][workType].push({
      slug:   node.slug,
      title:  node.title,
      ported: fs.existsSync(path.join(PAGES_DIR, node.slug + '.html')),
    });
  }
  return map;
}

// buildDepartmentMeta — display metadata per department/workType, mirroring buildArcMeta.
// Stored in index.json so the ecosystem hub has no hard-coded department tables.
function buildDepartmentMeta(departmentsDef) {
  const meta = {};
  for (const [id, def] of Object.entries(departmentsDef || {})) {
    if (id.startsWith('_')) continue;
    const workTypes = {};
    for (const [wid, w] of Object.entries(def.workTypes || {})) {
      workTypes[wid] = { label: w.label || wid };
    }
    meta[id] = {
      label:     def.label || id,
      default:   !!def.default,
      workTypes,
    };
  }
  return meta;
}

// ── I/O — only runs when executed directly ────────────────────────────────────

if (require.main === module) {
  const nodes        = JSON.parse(fs.readFileSync(NODES_IN,  'utf8'));
  const arcsDef      = JSON.parse(fs.readFileSync(ARCS_IN,   'utf8'));
  const viewmodels   = fs.existsSync(VIEWMODELS_IN)
    ? JSON.parse(fs.readFileSync(VIEWMODELS_IN, 'utf8'))
    : {};
  const departmentsDef = fs.existsSync(DEPARTMENTS_IN)
    ? JSON.parse(fs.readFileSync(DEPARTMENTS_IN, 'utf8'))
    : {};
  const scopeIndex = fs.existsSync(SCOPE_INDEX_IN)
    ? JSON.parse(fs.readFileSync(SCOPE_INDEX_IN, 'utf8'))
    : {};

  const dupes = findDuplicateSlugs(nodes);
  if (dupes.length) {
    for (const { slug, count } of dupes) {
      logger.error({ code: CODES.SLUG_DUPLICATE, message: `slug appears ${count} times in data/nodes.json — slug must be globally unique`, slug, count });
    }
    console.error(`[build-index] BLOCKED — ${dupes.length} duplicate slug(s) found. Fix data/nodes.json before rebuilding.`);
    process.exit(1);
  }

  // Auto-discovery: a pages/*.html file with no nodes.json entry gets a
  // synthetic node (title scraped from <title>, department/workType from
  // <meta> tags or the registry default) so it's visible in departmentMap
  // and build-health.html without anyone hand-editing nodes.json first. Never
  // written back to nodes.json — see lib/auto-discover-nodes.js's header.
  const nodeSlugsForDiscovery = nodes.map(n => n.slug);
  const viewmodelSlugs = Object.keys(viewmodels).filter(k => !k.startsWith('_'));
  const discovered = discoverOrphanNodes(getPageSlugs(), nodeSlugsForDiscovery, AUTO_DISCOVERY_EXCLUSIONS, viewmodelSlugs, readPageFromDisk, departmentsDef);
  const allNodes = nodes.concat(discovered);

  const slugMap        = buildSlugMap(allNodes, arcsDef, viewmodels);
  const arcMap         = buildArcMap(allNodes, arcsDef, slugMap);
  const arcMeta        = buildArcMeta(arcsDef);
  const supportedLangs = buildSupportedLangs();
  const pageLanguageMap = extendPageLanguageMapWithShellPages(
    buildPageLanguageMap(slugMap, viewmodels, scopeIndex),
    getPageSlugs(),
    scopeIndex,
    slug => fs.readFileSync(path.join(PAGES_DIR, slug + '.html'), 'utf8')
  );
  const sourceOnlyScopes = buildSourceOnlyScopes(scopeIndex);
  const departmentMap  = buildDepartmentMap(allNodes, departmentsDef);
  const departmentMeta = buildDepartmentMeta(departmentsDef);

  const content = {
    nodeCount:          allNodes.length,
    curatedNodeCount:   nodes.length,
    autoDiscoveredCount: discovered.length,
    arcCount:     Object.keys(arcMap).length,
    supportedLangs,
    pageLanguageMap,
    sourceOnlyScopes,
    slugMap,
    arcMap,
    arcMeta,
    departmentMap,
    departmentMeta
  };
  const index = {
    contentFingerprint: contentFingerprint(content),
    ...content,
  };

  fs.writeFileSync(INDEX_OUT, JSON.stringify(index, null, 2));

  console.log(`[build-index] Done.`);
  console.log(`  nodes       : ${index.nodeCount} (${index.curatedNodeCount} curated, ${index.autoDiscoveredCount} auto-discovered)`);
  console.log(`  arcs        : ${index.arcCount}`);
  console.log(`  departments : ${Object.keys(departmentMap).length}`);
  console.log(`  output      : ${INDEX_OUT}`);
}

