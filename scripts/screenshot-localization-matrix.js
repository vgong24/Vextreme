#!/usr/bin/env node
/**
 * VEXTREME — scripts/screenshot-localization-matrix.js
 *
 * Site-scale localization screenshot orchestrator.
 *
 * The matrix is derived, never hand-maintained:
 *   real pages/*.html × data/index.json.pageLanguageMap[slug].completeLangs
 *
 * availableLangs remains the user-facing partial-translation surface.
 * completeLangs is the stricter evidence gate: only locales whose complete
 * runtime scope set matches EN are eligible for localized screenshot identity.
 *
 * Usage:
 *   node scripts/screenshot-localization-matrix.js --dry-run [--slug <slug>] [--locale <locale>]
 *   node scripts/screenshot-localization-matrix.js --assets-root ../Vextreme-Assets [--slug <slug>] [--locale <locale>]
 *
 * Real execution requires an explicit Vextreme-Assets checkout. Captures are
 * written to a temporary directory, ingested through the Assets-owned contract,
 * then removed locally. One Chromium process is reused across the whole matrix;
 * each cell receives a fresh browser context.
 *
 * LATTICE:BEGIN — generated by lib/build-lattice-headers.js from docs/lattice-map.json. Do not hand-edit; edit the JSON and regenerate.
 *   role      : page × complete-locale screenshot matrix orchestrator — derives eligible evidence cells from pageLanguageMap and reuses the general screenshot engine
 *   reads     : data/index.json (pageLanguageMap[slug].completeLangs)
 *               lib/audit-pages.js (getPageSlugs real screen inventory)
 *               scripts/screenshot-page.js (shared browser/session + verified locale capture engine)
 *               explicit Vextreme-Assets/scripts/ingest-screenshot-evidence.mjs contract
 *   writes    : temporary PNG captures under the OS temp directory (removed after ingestion)
 *               Vextreme-Assets structured screenshot evidence through the Assets-owned ingest contract
 *   loaded-by : package.json localization:screenshots command
 *               manual run: node scripts/screenshot-localization-matrix.js [--dry-run|--assets-root <checkout>]
 *   tested-by : tests/44-page-health.test.js (matrix formation, complete-locale gate, and Assets-first execution contract)
 *
 *   CHANGE MAP — if you touch X here, also check:
 *     pageLanguageMap or completeLangs schema changed:
 *       - lib/build-index.js (projection owner)
 *       - docs/architecture/06-i18n.md
 *       - tests/01-content-pipeline.test.js
 *     capture engine contract changed:
 *       - scripts/screenshot-page.js
 *       - tests/44-page-health.test.js
 *     Vextreme-Assets ingest arguments or evidence schema changed:
 *       - Vextreme-Assets/scripts/ingest-screenshot-evidence.mjs (custody owner)
 *       - scripts/screenshot-page.js (per-cell handoff)
 * LATTICE:END
 */

'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');
const { getPageSlugs } = require('../lib/audit-pages');
const {
  captureLocaleCell,
  createCaptureSession,
  sourceCommit,
} = require('./screenshot-page');

const ROOT = path.join(__dirname, '..');
const INDEX_PATH = path.join(ROOT, 'data', 'index.json');
const SAFE_SLUG = /^[a-z0-9][a-z0-9-]*$/;
const SAFE_LOCALE = /^[a-z0-9][a-z0-9-]*$/;

function parseArgs(argv) {
  const options = {
    assetsRoot: process.env.VEXTREME_ASSETS_ROOT || null,
    dryRun: false,
    slug: null,
    locale: null,
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--assets-root') {
      options.assetsRoot = argv[++i];
      if (!options.assetsRoot) throw new Error('--assets-root requires a path');
    } else if (arg === '--dry-run') {
      options.dryRun = true;
    } else if (arg === '--slug') {
      options.slug = argv[++i];
      if (!options.slug || !SAFE_SLUG.test(options.slug)) throw new Error('--slug requires a safe page slug');
    } else if (arg === '--locale') {
      options.locale = argv[++i];
      if (!options.locale || !SAFE_LOCALE.test(options.locale)) throw new Error('--locale requires a safe locale');
    } else {
      throw new Error('unknown argument: ' + arg);
    }
  }

  if (options.assetsRoot) options.assetsRoot = path.resolve(options.assetsRoot);
  return options;
}

function buildCaptureMatrix(index, pageSlugs, filters = {}) {
  const realPages = new Set(pageSlugs || []);
  const pageLanguageMap = index && index.pageLanguageMap || {};
  const cells = [];

  for (const slug of Object.keys(pageLanguageMap).sort()) {
    if (!realPages.has(slug)) continue;
    if (filters.slug && slug !== filters.slug) continue;

    const coverage = pageLanguageMap[slug] || {};
    const completeLangs = Array.isArray(coverage.completeLangs) ? coverage.completeLangs : [];
    for (const locale of completeLangs) {
      if (filters.locale && locale !== filters.locale) continue;
      cells.push({ slug, locale });
    }
  }

  return cells;
}

function assetsIngestPath(assetsRoot) {
  return path.join(assetsRoot, 'scripts', 'ingest-screenshot-evidence.mjs');
}

function assertAssetsCheckout(assetsRoot) {
  if (!assetsRoot) {
    throw new Error('real matrix capture requires --assets-root <Vextreme-Assets checkout>; use --dry-run to inspect without writing');
  }
  const ingest = assetsIngestPath(assetsRoot);
  if (!fs.existsSync(ingest)) {
    throw new Error('Vextreme-Assets screenshot ingest contract not found: ' + ingest);
  }
  return ingest;
}

function validateAssetsEvidence(assetsRoot) {
  const ingest = assertAssetsCheckout(assetsRoot);
  execFileSync(process.execPath, [ingest, '--check', '--root', assetsRoot], {
    cwd: assetsRoot,
    stdio: 'inherit',
  });
}

function readIndex() {
  return JSON.parse(fs.readFileSync(INDEX_PATH, 'utf8'));
}

function renderDryRun(cells) {
  return {
    schemaVersion: 'vextreme.localization-screenshot-matrix/v1',
    mode: 'dry-run',
    cells: cells.length,
    matrix: cells,
  };
}

async function runMatrix(options) {
  const index = readIndex();
  const cells = buildCaptureMatrix(index, getPageSlugs(), options);

  if (!cells.length) {
    const qualifier = [options.slug && `slug=${options.slug}`, options.locale && `locale=${options.locale}`]
      .filter(Boolean)
      .join(', ');
    throw new Error('no complete page-locale screenshot cells' + (qualifier ? ' for ' + qualifier : ''));
  }

  if (options.dryRun) {
    const result = renderDryRun(cells);
    process.stdout.write(JSON.stringify(result, null, 2) + '\n');
    return result;
  }

  assertAssetsCheckout(options.assetsRoot);

  const commit = sourceCommit();
  const tempRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'vextreme-localization-matrix-'));
  const session = await createCaptureSession(cells[0].slug);
  let completed = 0;

  try {
    for (const cell of cells) {
      process.stdout.write(`[${completed + 1}/${cells.length}] ${cell.slug} / ${cell.locale}\n`);
      await captureLocaleCell(session, {
        slug: cell.slug,
        locale: cell.locale,
        outDir: tempRoot,
        assetsRoot: options.assetsRoot,
        commit,
      });
      completed += 1;
    }
  } finally {
    await session.close();
    fs.rmSync(tempRoot, { recursive: true, force: true });
  }

  validateAssetsEvidence(options.assetsRoot);

  const result = {
    schemaVersion: 'vextreme.localization-screenshot-matrix/v1',
    mode: 'capture',
    sourceCommit: commit,
    cells: completed,
    assetsRoot: options.assetsRoot,
  };
  process.stdout.write(JSON.stringify(result, null, 2) + '\n');
  return result;
}

async function main(argv = process.argv.slice(2)) {
  return runMatrix(parseArgs(argv));
}

if (require.main === module) {
  main().catch(error => {
    console.error('[screenshot-localization-matrix] ' + error.message);
    process.exitCode = 1;
  });
}

module.exports = {
  INDEX_PATH,
  ROOT,
  assertAssetsCheckout,
  assetsIngestPath,
  buildCaptureMatrix,
  main,
  parseArgs,
  readIndex,
  renderDryRun,
  runMatrix,
  validateAssetsEvidence,
};

