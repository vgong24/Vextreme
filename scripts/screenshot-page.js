'use strict';

const http = require('http');
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const PLAYWRIGHT_PATH = '/opt/node22/lib/node_modules/playwright';
const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'docs', 'screenshots');
const CDN_PREFIX = 'https://cdn.jsdelivr.net/gh/vgong24/vextreme@main';
const VIEWPORT = { width: 1280, height: 900 };

function loadChromium() {
  return require(PLAYWRIGHT_PATH).chromium;
}

function parseArgs(argv) {
  const positional = [];
  let assetsRoot = process.env.VEXTREME_ASSETS_ROOT || null;
  let locale = null;
  let outDir = OUT_DIR;

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--assets-root') {
      assetsRoot = argv[++i];
      if (!assetsRoot) throw new Error('--assets-root requires a path');
    } else if (arg === '--locale') {
      locale = argv[++i];
      if (!locale || locale.startsWith('--')) throw new Error('--locale requires a language');
    } else if (arg === '--out-dir') {
      const value = argv[++i];
      if (!value || value.startsWith('--')) throw new Error('--out-dir requires a path');
      outDir = path.resolve(value);
    } else if (arg.startsWith('--')) {
      throw new Error('unknown argument: ' + arg);
    } else {
      positional.push(arg);
    }
  }

  if (positional.length > 2) {
    throw new Error('usage: node scripts/screenshot-page.js [slug] [lang] [--locale <lang>] [--assets-root <path>] [--out-dir <path>]');
  }
  if (locale && positional[1]) {
    throw new Error('use either positional [lang] pair mode or --locale single-cell mode, not both');
  }

  return {
    slug: positional[0] || 'claude-answers-the-doubt',
    lang: positional[1] || 'ja',
    locale,
    assetsRoot: assetsRoot ? path.resolve(assetsRoot) : null,
    outDir,
  };
}

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.svg': 'image/svg+xml',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.ttf': 'font/ttf',
};

function mimeFor(filePath) {
  return MIME[path.extname(filePath)] || 'text/plain';
}

function startServer(defaultSlug) {
  return new Promise((resolve) => {
    const server = http.createServer((req, res) => {
      const urlPath = req.url.split('?')[0];
      const fallback = '/pages/' + (defaultSlug || 'claude-answers-the-doubt') + '.html';
      const filePath = path.join(ROOT, urlPath === '/' ? fallback : urlPath);

      fs.readFile(filePath, (err, data) => {
        if (err) {
          res.writeHead(404);
          res.end('Not found: ' + filePath);
          return;
        }
        res.writeHead(200, { 'Content-Type': mimeFor(filePath) });
        res.end(data);
      });
    });

    server.listen(0, '127.0.0.1', () => {
      const { port } = server.address();
      resolve({ server, port });
    });
  });
}

function localPathFor(cdnUrl) {
  const relative = cdnUrl.replace(CDN_PREFIX, '');
  const clean = relative.split('?')[0];
  return path.join(ROOT, clean);
}

async function installLocalCdnRoute(page) {
  await page.route(`${CDN_PREFIX}/**`, async (route) => {
    const local = localPathFor(route.request().url());
    if (fs.existsSync(local)) {
      const body = fs.readFileSync(local);
      await route.fulfill({ status: 200, contentType: mimeFor(local), body });
    } else {
      console.warn(`  [cdn-miss] ${route.request().url()}`);
      await route.continue();
    }
  });
}

async function screenshotPage(page, outPath, label) {
  await page.waitForTimeout(1200);
  await page.screenshot({ path: outPath, fullPage: true });
  console.log(`  [screenshot] ${label} → ${path.relative(ROOT, outPath)}`);
}

function sourceCommit() {
  const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: ROOT, encoding: 'utf8' }).trim();
  if (!/^[0-9a-f]{40}$/i.test(commit)) throw new Error('could not resolve an exact Vextreme source commit');
  return commit.toLowerCase();
}

function publishScreenshotEvidence({ outPath, locale, slug, assetsRoot, commit }) {
  if (!assetsRoot) return;
  const ingest = path.join(assetsRoot, 'scripts', 'ingest-screenshot-evidence.mjs');
  if (!fs.existsSync(ingest)) {
    throw new Error('Vextreme-Assets screenshot ingest contract not found: ' + ingest);
  }
  execFileSync(process.execPath, [
    ingest,
    '--file', outPath,
    '--namespace', 'vextreme',
    '--slug', slug,
    '--locale', locale,
    '--theme', 'default',
    '--viewport', String(VIEWPORT.width),
    '--source-repo', 'vgong24/Vextreme',
    '--source-commit', commit,
    '--source-path', 'pages/' + slug + '.html',
    '--capture-kind', 'localization',
  ], { cwd: assetsRoot, stdio: 'inherit' });
  console.log(`  [assets] ${locale.toUpperCase()} → structured screenshot evidence (${commit.slice(0, 12)})`);
}

async function createCaptureSession(defaultSlug) {
  const { server, port } = await startServer(defaultSlug);
  const chromium = loadChromium();
  const launchOptions = {
    executablePath: process.env.VEX_CHROMIUM_PATH || '/opt/pw-browsers/chromium-1194/chrome-linux/chrome',
    args: ['--no-sandbox'],
  };
  let browser;
  try {
    browser = await chromium.launch(launchOptions);
  } catch (error) {
    await new Promise(resolve => server.close(resolve));
    throw error;
  }
  return {
    server,
    browser,
    baseUrl: `http://127.0.0.1:${port}`,
    async close() {
      await browser.close();
      await new Promise(resolve => server.close(resolve));
    },
  };
}

async function switchLocale(page, locale) {
  const fabBtn = page.locator('#vex-lang-fab-btn');
  const fabExists = await fabBtn.count();
  if (!fabExists) {
    throw new Error('FAB button not found — refusing to label a localization screenshot without a verified language switch');
  }

  await fabBtn.click();
  await page.waitForTimeout(400);

  const langItem = page.locator(`.vex-lang-item[data-lang="${locale}"]`);
  const langExists = await langItem.count();
  if (!langExists) {
    throw new Error(`No FAB item found for lang="${locale}" — refusing to capture mislabeled evidence`);
  }

  await langItem.click();
  await page.waitForFunction((expected) => {
    try { return localStorage.getItem('vex-lang') === expected; } catch (error) { return false; }
  }, locale);
  await page.waitForTimeout(250);
}

async function captureLocaleCell(session, options) {
  const slug = options.slug;
  const locale = options.locale || 'en';
  const outDir = path.resolve(options.outDir || OUT_DIR);
  const assetsRoot = options.assetsRoot ? path.resolve(options.assetsRoot) : null;
  const commit = options.commit || sourceCommit();
  const pageFile = path.join(ROOT, 'pages', slug + '.html');
  if (!fs.existsSync(pageFile)) throw new Error(`pages/${slug}.html does not exist`);

  fs.mkdirSync(outDir, { recursive: true });
  const context = await session.browser.newContext({ viewport: VIEWPORT });
  const page = await context.newPage();

  try {
    await installLocalCdnRoute(page);
    const pageUrl = `${session.baseUrl}/pages/${slug}.html`;
    console.log(`\nLoading: ${pageUrl} [${locale}]`);
    await page.goto(pageUrl, { waitUntil: 'networkidle' });

    if (locale !== 'en') await switchLocale(page, locale);
    await page.evaluate(() => window.scrollTo(0, 0));

    const outPath = path.join(outDir, `${slug}-${locale}.png`);
    await screenshotPage(page, outPath, locale === 'en' ? 'EN (default)' : `${locale.toUpperCase()} (after verified FAB switch)`);
    publishScreenshotEvidence({ outPath, locale, slug, assetsRoot, commit });
    return { slug, locale, outPath };
  } finally {
    await context.close();
  }
}

async function runCli(argv = process.argv.slice(2)) {
  const options = parseArgs(argv);
  const session = await createCaptureSession(options.slug);
  const commit = sourceCommit();
  const captures = [];

  try {
    if (options.locale) {
      captures.push(await captureLocaleCell(session, {
        slug: options.slug,
        locale: options.locale,
        outDir: options.outDir,
        assetsRoot: options.assetsRoot,
        commit,
      }));
    } else {
      captures.push(await captureLocaleCell(session, {
        slug: options.slug,
        locale: 'en',
        outDir: options.outDir,
        assetsRoot: options.assetsRoot,
        commit,
      }));
      if (options.lang !== 'en') {
        captures.push(await captureLocaleCell(session, {
          slug: options.slug,
          locale: options.lang,
          outDir: options.outDir,
          assetsRoot: options.assetsRoot,
          commit,
        }));
      }
    }
  } finally {
    await session.close();
  }

  console.log('\nDone.');
  for (const capture of captures) {
    console.log(`  ${capture.locale.toUpperCase()} : ${path.relative(ROOT, capture.outPath)}`);
  }
  if (options.assetsRoot) console.log(`  Assets evidence checkout: ${options.assetsRoot}`);
  return captures;
}

if (require.main === module) {
  runCli().catch(error => {
    console.error('[screenshot-page] ' + error.message);
    process.exitCode = 1;
  });
}

